// Live cross-tool context injection (plan §6.A).
//
// Writes a distilled, CROSS-PROJECT digest of your brain into each installed AI
// CLI's native global context file — the file that tool auto-loads on startup in
// ANY folder. Result: launching claude / codex / ags anywhere gives it knowledge
// spanning all your projects ("other folder knowledge"), with no wrapper.
//
// SAFE: the digest goes inside a delimited managed block. Anything you wrote in
// those files outside the block is preserved verbatim; re-injecting only rewrites
// the block. Removing the block cleanly uninstalls it.
import { existsSync, readFileSync, writeFileSync, mkdirSync, realpathSync } from 'node:fs';
import { join, dirname, basename, resolve } from 'node:path';
import { homedir } from 'node:os';
import { openDb } from './db.mjs';
import { MEMORY_DB, REPO_WIKI, REPO_ROOT } from './paths.mjs';
import { scrubText } from './scrub.mjs';
import { liveOnly } from './lifecycle.mjs';
import { collapseDuplicates } from './memkey.mjs';
import { TARGETS, detectedTargets } from './wire-targets.mjs';

const h = (...p) => join(homedir(), ...p);
const START = '<!-- BRAIN:START (auto-generated by claude-brain — this block is overwritten on each sync; edit outside it) -->';
const END = '<!-- BRAIN:END -->';

// Each tool's global context file — the PUSH channel of the one registry
// (bin/lib/wire-targets.mjs), so this writer and `brain doctor`'s checkPush()
// can never drift apart on paths, display names, or "is it installed?".
// Confirmed conventions (all encoded as registry `push.file()`):
//   Claude Code (×3 profiles) → ~/.claude*/CLAUDE.md   (they do NOT share one)
//   Codex                     → ~/.codex/AGENTS.md
//   Antigravity CLI (agy)     → ~/.gemini/GEMINI.md  (agy keeps its data under ~/.gemini)
//
// When two targets resolve to the same push file, the rule is WRITE ONCE,
// REPORT BOTH. Iterating the registry (or a config.json inject.targets list)
// naively would splice the same file twice per run — churn, and a second run
// that is no longer a no-op. Grouping happens on the RESOLVED real
// path, not the string, so a symlinked equivalence dedupes too.
// (Project-level Antigravity/Codex read a per-repo AGENTS.md — injectFolder().)
//
// Override any of this via config.json → inject.targets (a plain
// {id,label,file[,dir]} list; those rows keep the simple "parent dir exists"
// install test and are deduped by resolved path just the same).
function registryTargets() {
  const detected = new Set(detectedTargets().map((t) => t.id));
  const out = [];
  for (const t of TARGETS) {
    if (typeof t.push?.file !== 'function') continue; // no global push channel by design
    let file;
    try { file = t.push.file(); } catch { continue; }
    out.push({ id: t.id, label: t.name, file, dir: dirname(file), installed: detected.has(t.id) });
  }
  return out;
}

const GENERIC = new Set([
  'how-it-works', 'what-changed', 'pattern', 'problem-solution', 'gotcha', 'why-it-exists',
  'trade-off', 'decision', 'validation', 'refactor', 'security_note', 'security-note',
  'verification', 'observation', 'summary', 'completion', 'discovery', 'feature', 'bugfix',
  'cleanup', 'task-completion', 'change',
]);

function targets() {
  try {
    const cfg = JSON.parse(readFileSync(join(REPO_ROOT, 'config.json'), 'utf8'));
    if (Array.isArray(cfg.inject?.targets) && cfg.inject.targets.length) {
      return cfg.inject.targets.map((t) => {
        const dir = t.dir || dirname(t.file);
        return { ...t, dir, installed: existsSync(dir) };
      });
    }
  } catch {}
  return registryTargets();
}

// Identity of a push file for dedupe purposes. Two targets are the same write
// iff this key matches. String compare is not enough: ~/.gemini could itself be
// a symlink, and a missed equivalence reintroduces the double write. So we
// resolve symlinks on the deepest existing ancestor and re-attach the rest —
// realpathSync() on the file itself throws when the file does not exist yet
// (the normal first-run case), which is exactly when a naive impl gives up.
function pushKey(file) {
  let p = resolve(file);
  const tail = [];
  for (let i = 0; i < 64; i++) {
    try { return join(realpathSync(p), ...tail); } catch {}
    const parent = dirname(p);
    if (parent === p) break; // hit the filesystem root, nothing resolvable
    tail.unshift(basename(p));
    p = parent;
  }
  return resolve(file);
}

// Group targets that write the SAME file into one write unit. A group is
// "installed" if ANY of its members is; its label names every member the write
// actually serves (e.g. "Kilo Code (VS Code) + Kilo Code (Cursor)"), so the
// report under-claims nothing and the file is spliced exactly once.
function pushGroups(list) {
  const byKey = new Map();
  for (const t of list) {
    const key = pushKey(t.file);
    const g = byKey.get(key);
    if (g) g.members.push(t);
    else byKey.set(key, { key, file: t.file, dir: t.dir, members: [t] });
  }
  return [...byKey.values()].map((g) => {
    const live = g.members.filter((m) => m.installed);
    const named = live.length ? live : g.members;
    return {
      ...g,
      installed: live.length > 0,
      ids: named.map((m) => m.id),
      label: named.map((m) => m.label).join(' + '),
      shared: named.length > 1,
    };
  });
}

// Build the concise cross-project digest (markdown). Kept small on purpose — this
// loads into EVERY session, so it's a map + pointers, not the whole wiki.
export function buildDigest() {
  if (!existsSync(MEMORY_DB)) return null;
  const db = openDb(MEMORY_DB, { readonly: true });
  try {
    // Counts, projects and themes are over live rows: a memory deleted in the
    // control panel must not resurface in a digest every CLI loads.
    const live = liveOnly(db);
    const now = db.prepare(`SELECT MAX(created_at_epoch) m FROM observations o WHERE 1=1${live}`).get().m || 0;
    const total = db.prepare(`SELECT COUNT(*) n FROM observations o WHERE 1=1${live}`).get().n;
    const projects = db
      .prepare(
        `SELECT project, COUNT(*) n, MAX(created_at) last, MAX(created_at_epoch) e
           FROM observations o WHERE 1=1${live} GROUP BY project ORDER BY e DESC LIMIT 20`
      )
      .all();

    // Overall recurring themes (skip generic type-ish tags).
    const rows = db.prepare(`SELECT concepts FROM observations o WHERE concepts IS NOT NULL AND concepts != ''${live}`).all();
    const cc = new Map();
    for (const r of rows) {
      try {
        for (const c of JSON.parse(r.concepts)) {
          const k = String(c).trim();
          if (k && !GENERIC.has(k.toLowerCase())) cc.set(k, (cc.get(k) || 0) + 1);
        }
      } catch {}
    }
    const themes = [...cc.entries()].sort((a, b) => b[1] - a[1]).slice(0, 15);

    const DAY = 86400000;
    const active = projects.filter((p) => now - p.e < 7 * DAY);

    // Empty / near-empty: the boastful "0 observations across 0 projects" block
    // is the single worst first impression across every CLI's global context
    // file. Swap in a brief, honest first-run note instead — the populated
    // path below is otherwise untouched.
    if (total === 0) {
      return scrubText(
        [
          '# Operator brain — cross-project memory',
          '',
          "> 🧠 **Open Agentic Brain and Memory** — no observations yet. It hasn't learned anything from you " +
            'yet, but it will as you work: use Claude Code, Codex, or Cursor normally and memory ' +
            'builds up automatically. Nothing to search or act on here yet.',
          '',
        ].join('\n')
      ).text;
    }

    const L = [];
    L.push('# Operator brain — cross-project memory');
    L.push('');
    L.push(`> 🧠 **Open Agentic Brain and Memory loaded** — **${total}** observations across **${projects.length}** projects are ` +
      `available to you as context right now. Search the full memory anytime with the \`brain_recall\` ` +
      `MCP tool, or \`brain_context\` for a ranked "what should I know before starting X". ` +
      `When the user asks to "load all my memory", call \`brain_context\` with that task for the ` +
      `cross-project overview. ` +
      `_(Acknowledge on your first reply so the user knows their brain is active, and that they can ` +
      `ask about any other project or app — something specific, or "load all my memory".)_`);
    L.push('');
    L.push(`_**${total}** observations across **${projects.length}** projects, distilled by Open Agentic Brain and Memory. ` +
      `Auto-synced so this context is available in every folder._`);
    L.push('');
    if (active.length) {
      L.push('## Active this week');
      for (const p of active) L.push(`- **${p.project}** — ${p.n} observations (last ${(p.last || '').slice(0, 10)})`);
      L.push('');
    }
    L.push('## All projects (most recent first)');
    for (const p of projects) L.push(`- **${p.project}** — ${p.n} obs, last ${(p.last || '').slice(0, 10)}`);
    L.push('');
    L.push('## Recurring themes across projects');
    L.push(themes.map(([c, n]) => `${c} (${n})`).join(' · '));
    L.push('');
    // Fold in the latest dream briefing if present (recent attention / rising concepts).
    const brief = join(REPO_WIKI, 'briefing.md');
    if (existsSync(brief)) {
      const b = readFileSync(brief, 'utf8').split('\n').filter((l) => l && !/^# /.test(l)).slice(0, 20).join('\n');
      if (b.trim()) { L.push('## Recent focus (from last dream)'); L.push(b); L.push(''); }
    }
    L.push('## Going deeper');
    L.push('- This is a summary map. The full memory lives in the native store (`~/.claude-brain/brain.db`).');
    L.push('- `brain_recall` (query, project, limit) pulls details for any project or topic above.');
    L.push('- `brain_context` (task) ranks what matters before starting a specific piece of work.');
    L.push('- From a terminal: `brain recall "<words>" --project "<p>"`.');
    L.push('- Or the Open Agentic Brain and Memory UI (localhost:37800) → Memory tab searches everything.');
    L.push('');
    // P8 (docs/specs/secret-scrubber.md §5.3): belt-and-braces scrub right before this
    // digest is written into CLAUDE.md/AGENTS.md — files that are frequently committed
    // to OTHER repos, the one path where a miss escapes the brain entirely. This is
    // an egress surface, not capture, so tier 5 stays on and redacts here (capture
    // paths treat tier 5 as review-only; see scrub.mjs).
    return scrubText(L.join('\n'), { entropyMode: 'redact' }).text;
  } finally {
    db.close();
  }
}

// Build a FOLDER-scoped digest: what the brain knows about ONE project. This is
// what Codex/ags get when launched in that repo (Claude Code gets it live from
// claude-mem instead). Bounded — recent work + key concepts + hot files.
export function buildFolderDigest(project) {
  if (!project || !existsSync(MEMORY_DB)) return { project, count: 0, digest: null };
  const db = openDb(MEMORY_DB, { readonly: true });
  try {
    const count = db.prepare(`SELECT COUNT(*) n FROM observations o WHERE project = ?${liveOnly(db)}`).get(project).n;
    if (!count) return { project, count: 0, digest: null };
    // "Recent work" names memories to every CLI: a row the user deleted in the
    // control panel must not be one of them.
    // …and names each memory once (memkey.mjs): over-fetch, then drop copies.
    const recent = collapseDuplicates(db, db
      .prepare(
        `SELECT id, project, title, subtitle, type, facts, concepts, files_modified, created_at
           FROM observations o WHERE project = ?${liveOnly(db)} ORDER BY created_at_epoch DESC LIMIT 75`
      )
      .all(project), { limit: 25 });
    const all = db.prepare(`SELECT concepts, files_modified FROM observations o WHERE project = ?${liveOnly(db)}`).all(project);

    const cc = new Map();
    const fc = new Map();
    for (const r of all) {
      try { for (const c of JSON.parse(r.concepts || '[]')) { const k = String(c).trim(); if (k && !GENERIC.has(k.toLowerCase())) cc.set(k, (cc.get(k) || 0) + 1); } } catch {}
      try { for (const f of JSON.parse(r.files_modified || '[]')) { const k = String(f).trim(); if (k) fc.set(k, (fc.get(k) || 0) + 1); } } catch {}
    }
    const themes = [...cc.entries()].sort((a, b) => b[1] - a[1]).slice(0, 12);
    const files = [...fc.entries()].sort((a, b) => b[1] - a[1]).slice(0, 15);

    const one = (s) => String(s ?? '').replace(/\n/g, ' ').trim();
    const L = [];
    L.push(`# ${project} — folder memory (from your brain)`);
    L.push('');
    L.push(`_${count} observations captured for this project, written by Open Agentic Brain and Memory so every CLI has this ` +
      `folder's history._`);
    L.push('');
    L.push('## Recent work here');
    for (const o of recent) {
      let fact = '';
      try { fact = (JSON.parse(o.facts || '[]')[0]) || ''; } catch {}
      L.push(`- **${one(o.title || o.subtitle || 'note')}** _(${one(o.type)}, ${(o.created_at || '').slice(0, 10)})_${fact ? ' — ' + one(fact).slice(0, 160) : ''}`);
    }
    L.push('');
    if (themes.length) { L.push('## Key concepts here'); L.push(themes.map(([c, n]) => `${c} (${n})`).join(' · ')); L.push(''); }
    if (files.length) { L.push('## Files most touched'); for (const [f, n] of files) L.push(`- \`${f}\` (${n})`); L.push(''); }
    L.push('## Going deeper');
    L.push('- Full detail is in the native store; use the `brain_recall` MCP tool or `brain recall "<words>"`.');
    L.push('- Cross-project map is in the global context file (`~/.codex/AGENTS.md`).');
    L.push('');
    // P8: same belt-and-braces scrub as buildDigest() — this writes into a
    // per-folder AGENTS.md, often committed to a repo this brain doesn't own.
    return { project, count, digest: scrubText(L.join('\n'), { entropyMode: 'redact' }).text };
  } finally {
    db.close();
  }
}

// Write a folder-scoped AGENTS.md INTO a repo, so Codex/ags launched there know
// this folder's history. Run from inside the repo (project inferred from folder
// name) or pass an explicit project. Dry-run by default. Managed-block safe.
export function injectFolder({ folder = process.cwd(), project, write = false, log = () => {} } = {}) {
  const proj = project || basename(folder);
  const { count, digest } = buildFolderDigest(proj);
  const file = join(folder, 'AGENTS.md');
  if (!digest) return { ok: false, project: proj, folder, file, count: 0, error: `No observations for project "${proj}". Work in this folder with any wired CLI once (capture is automatic), then re-run.` };
  const existed = existsSync(file);
  const hadBlock = existed && readFileSync(file, 'utf8').includes(START);
  if (!write) {
    return { ok: true, project: proj, folder, file, count, digest, action: existed ? (hadBlock ? 'would update block' : 'would append block (keeps your content)') : 'would create AGENTS.md', wrote: false };
  }
  const r = spliceBlock(file, digest);
  const action = r.changed ? (r.existed ? (hadBlock ? 'updated block' : 'appended block (kept your content)') : 'created AGENTS.md') : 'unchanged';
  log(`  ${proj}: ${action} → ${file}`);
  return { ok: true, project: proj, folder, file, count, action, wrote: true };
}

// The context file each CLI auto-loads on launch (verified: agy reads GEMINI.md,
// NOT AGENTS.md; codex reads AGENTS.md; claude reads CLAUDE.md).
export const LAUNCH_FILES = {
  claude: h('.claude', 'CLAUDE.md'),
  codex: h('.codex', 'AGENTS.md'),
  agy: h('.gemini', 'GEMINI.md'),
};

// Combined launch context = cross-project MAP (breadth) + THIS folder's recent
// memory (depth) + a pointer to the live MCP tools. This is what makes launching
// any CLI feel like claude-mem's SessionStart: fresh, folder-aware, auto-loaded.
export function buildLaunchContext(folder = process.cwd()) {
  const parts = [];
  const map = buildDigest();
  if (map) parts.push(map);
  const fd = buildFolderDigest(basename(folder));
  if (fd.digest) parts.push('---\n\n' + fd.digest);
  parts.push(
    '---\n\n## Live memory (search for more)\n' +
      'The `agentic-brain` MCP server is wired in — use `brain_recall` / `brain_context` to pull ' +
      'deeper detail for any project, file, or topic above. This context is a summary; the full brain is searchable.'
  );
  return parts.join('\n\n');
}

// Refresh a tool's auto-loaded context file with fresh folder-aware context
// (managed BRAIN block; human content preserved). Call right before launching it.
export function refreshLaunchContext(tool, folder = process.cwd()) {
  const file = LAUNCH_FILES[tool];
  if (!file) throw new Error(`unknown tool: ${tool} (expected claude|codex|agy)`);
  spliceBlock(file, buildLaunchContext(folder));
  return { tool, file };
}

// Splice the managed block into a file, preserving all content outside it.
function spliceBlock(file, block) {
  const managed = `${START}\n${block}\n${END}`;
  if (!existsSync(file)) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, managed + '\n');
    return { existed: false, changed: true };
  }
  const cur = readFileSync(file, 'utf8');
  const a = cur.indexOf(START);
  const b = cur.indexOf(END);
  let next;
  if (a !== -1 && b !== -1 && b > a) {
    next = cur.slice(0, a) + managed + cur.slice(b + END.length);
  } else {
    next = cur.trimEnd() + '\n\n' + managed + '\n';
  }
  if (next === cur) return { existed: true, changed: false };
  writeFileSync(file, next);
  return { existed: true, changed: true };
}

// Preview or apply injection. Dry-run by default (write=false): reports what WOULD
// change without touching any file. Only writes to installed tools.
export function injectContext({ write = false, log = () => {} } = {}) {
  const digest = buildDigest();
  if (!digest) return { ok: false, error: 'No memory DB — nothing to inject.', digest: '', results: [] };
  const results = [];
  // One row per DISTINCT push file, never per registry row: targets sharing a
  // file are written once and reported once, naming every tool served. `ids` carries every tool the row
  // serves for consumers that key off ids rather than labels.
  for (const t of pushGroups(targets())) {
    const base = { id: t.ids[0] ?? null, ids: t.ids, label: t.label, file: t.file, shared: t.shared };
    if (!t.installed) { results.push({ ...base, installed: false, action: 'skipped (not installed)' }); continue; }
    const existed = existsSync(t.file);
    let hasBlock = false, otherBytes = 0;
    if (existed) {
      const cur = readFileSync(t.file, 'utf8');
      hasBlock = cur.includes(START);
      otherBytes = cur.replace(new RegExp(`${escapeRe(START)}[\\s\\S]*?${escapeRe(END)}`), '').trim().length;
    }
    if (write) {
      const r = spliceBlock(t.file, digest);
      results.push({ ...base, installed: true, action: r.changed ? (r.existed ? (hasBlock ? 'updated block' : 'appended block (kept your content)') : 'created file') : 'unchanged', preservedBytes: otherBytes });
      log(`  ${t.label}: ${results[results.length - 1].action} → ${t.file}`);
    } else {
      results.push({ ...base, installed: true, action: existed ? (hasBlock ? 'would update block' : 'would append block (keeps your content)') : 'would create file', preservedBytes: otherBytes });
    }
  }
  return { ok: true, digest, results, wrote: write };
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
